def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--unicode-data', type=Path, required=True, help='Pinned Unicode14 UnicodeData.txt; hash is verified before generation')
    parser.add_argument('--write', action='store_true', help='Create missing generated files; never replace a file')
    args = parser.parse_args()
    for path, source in generated_sources(args.unicode_data).items():
        if args.write:
            with path.open('x', encoding='utf-8', newline='\n') as stream:
                stream.write(source)
        elif path.read_bytes() != source.encode():
            raise ValueError('Frozen table differs: ' + str(path))


if __name__ == '__main__':
    main()
